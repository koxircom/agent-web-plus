import assert from "node:assert/strict";
import test from "node:test";
import { mkdtempSync, mkdirSync, readFileSync, readdirSync, writeFileSync, symlinkSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { setTimeout as delay } from "node:timers/promises";
import { createJiti } from "jiti";
const jiti = createJiti(import.meta.url);
const store = await jiti.import("./learning-store.ts");
const runtime = await jiti.import("./learning-runtime.ts");
const dir = mkdtempSync(join(tmpdir(), "pi-learning-unit-"));
process.env.PI_CODING_AGENT_DIR = join(dir, "agent");
const project = join(dir, "project"); const other = join(dir, "other"); mkdirSync(project); mkdirSync(other);
const row = { title: "图片保存验证", content: "图片保存必须检查生成文件，不以接口成功作为依据。", kind: "experience" };
async function until(fn) { for (let i=0;i<100;i++) { if (fn()) return; await delay(20); } throw Error("状态超时"); }
test.after(() => rmSync(dir, { recursive: true, force: true }));
test("defaults off, project isolation, dedupe, dismissal and guarded skill adoption", () => {
  assert.equal(store.learningEnabled(), false); store.setLearningEnabled(true);
  store.saveLearningLessons(project, [row, row]);
  const lesson = store.learningStatus(project).lessons[0]; assert.equal(lesson.occurrences, 2);
  assert.equal(store.learningStatus(other).lessons.length, 0);
  assert.equal(store.relevantLearning(project, "检查图片保存").length, 1);
  store.dismissLearningLesson(project, lesson.id); store.saveLearningLessons(project, [row]);
  assert.equal(store.relevantLearning(project, "图片保存").length, 0);
  store.saveLearningLessons(project, [{ ...row, kind: "skill" }]);
  const skill = store.learningStatus(project).lessons[0]; assert.equal(skill.status, "candidate");
  store.adoptLearningSkill(project, skill.id); store.adoptLearningSkill(project, skill.id);
  const published = store.learningStatus(project).lessons[0]; assert.match(readFileSync(published.skillPath,"utf8"), /name: pi-web-learned-/);
  writeFileSync(published.skillPath, "用户内容"); assert.throws(() => store.adoptLearningSkill(project,skill.id), /保留原文件/);
  assert.equal(readFileSync(published.skillPath,"utf8"),"用户内容");
  assert.throws(() => store.adoptLearningSkill(project, "../../bad"), /无效/);
});
test("redacts credentials, excludes images, preserves task and final evidence", () => {
  const secret = "sk-1234567890abcdefghijklmnop";
  const result = runtime.learningTranscript([{role:"user", content:"以后图片保存 password=foo " + secret}, ...Array.from({length:30},()=>({role:"toolResult", content:"x".repeat(2000)})), {role:"custom", content:"历史经验不能重复作为新证据"}, {role:"assistant", content:[{type:"image", data:"private-image"},{type:"text",text:"最终生成文件已检查"}]}]);
  assert.ok(result.length <= 12000); assert.match(result,/以后图片保存/); assert.match(result,/最终生成文件已检查/);
  assert.ok(!result.includes(secret) && !result.includes("password=foo") && !result.includes("private-image") && !result.includes("历史经验不能重复作为新证据"));
  assert.equal(runtime.learningTranscript([{role:"user",content:"你好"},{role:"assistant",content:"你好"}]),null);
  assert.throws(() => store.normalizeLearningOutput({lessons:[{title:"bad"}]}),/无效/);
});
test("single queue survives cancellation of an uncooperative model; budget and recall are native", async () => {
  const cwd = other; store.setLearningEnabled(true); let runs=0;
  const hanging = {cwd,id:"hanging",run:()=>{runs++;return new Promise(()=>{});}};
  assert.equal(runtime.enqueueLearningReview(hanging),true); assert.equal(runtime.enqueueLearningReview(hanging),false);
  await until(()=>runs===1); store.setLearningEnabled(false); runtime.cancelLearningReviews();
  await until(()=>store.learningStatus(cwd).lastReview.status==="skipped");
  store.setLearningEnabled(true);
  for(let i=0;i<10;i++) store.saveLearningReview(cwd,{id:"budget"+i,status:"completed",updatedAt:new Date().toISOString()});
  assert.equal(runtime.enqueueLearningReview({cwd,id:"overbudget",run:async()=>{throw Error("must not call");}}),false);
  assert.equal(store.learningStatus(cwd).lastReview.status,"skipped");
  store.saveLearningLessons(cwd,[row]); let callback;
  runtime.createLearningRecallExtension(cwd).factory({on:(event,fn)=>{assert.equal(event,"before_agent_start");callback=fn;}});
  const recalled=callback({prompt:"检查图片保存"}); assert.equal(recalled.message.display,false); assert.match(recalled.message.content,/不得覆盖/);
  assert.equal(callback({type:"before_agent_start",message:{}}),undefined);
  store.setLearningEnabled(false); assert.equal(callback({prompt:"图片保存"}),undefined);
});
test("rejects symlink stores and exposes interrupted reviews without replaying them",()=>{
  const another = mkdtempSync(join(dir,"agent-")); mkdirSync(join(another,"learning")); symlinkSync(project,join(another,"learning","projects"));
  assert.throws(()=>store.saveLearningLessons(other,[row],another),/符号链接/);
  store.saveLearningReview(project,{id:"interrupted",status:"running",updatedAt:new Date(Date.now()-13*60000).toISOString()});
  assert.equal(store.learningStatus(project).lastReview.status,"failed");
  assert.ok(store.reviewAlreadySeen(project,"interrupted"));
});
