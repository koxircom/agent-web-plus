test('exact native handoff publishes the shared queue before releasing transport originals',async()=>{
 const {id,requestId,meta,runtime}=fixture(),events=[];
 runtime.listeners.add(e=>events.push([e.type,inbox.getPromptReceipt(id,requestId).status]));
 runtime.json=async()=>({id:engine.submissionUuid(requestId),status:'queued',nativeQueueConfirmed:true,nativeQueueId:'native-1',queuedSubmissions:[{id:'native-1',text:'原文',status:'queued',mode:'queue',clientRequestId:requestId}]});
 const command={type:'prompt',message:'原文',requestId,streamingBehavior:'followUp'};
 await inbox.runPromptDelivery(id,requestId,command,()=>runtime.send(command));
 assert.equal(inbox.getPromptReceipt(id,requestId).status,'committed');
 assert.equal(events.find(([kind])=>kind==='queue_update')[1],'pending');
 assert.equal(runtime.meta.submissions[0].clientRequestId,requestId);
 await runtime.accept({epoch:'e',sequence:2,rows:[],meta},0);
 assert.equal(runtime.meta.submissions[0].id,'native-1','old in-flight poll cannot erase a confirmed queue');
 runtime.json=async()=>({queuedMessages:{steering:[],followUp:[]},queuedSubmissions:[]});
 await runtime.send({type:'delete_queued_message',token:'native-1'});
 await runtime.accept({epoch:'e',sequence:3,rows:[],meta:{...meta,submissions:[{id:'native-1',text:'原文',status:'queued',mode:'queue'}]}},1);
 assert.deepEqual(runtime.meta.submissions,[],'old poll cannot resurrect a deleted native item');
});
