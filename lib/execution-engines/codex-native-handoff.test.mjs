 runtime.listeners.add(event=>events.push(event));runtime.json=async()=>({version:2,queuedMessages:{steering:[],followUp:['相同任务','相同任务']},queuedSubmissions:rows});
 const reply=await runtime.send({type:'reorder_queued_message',tokens:['native-a','native-b'],token:'native-b',targetToken:'native-a'});
