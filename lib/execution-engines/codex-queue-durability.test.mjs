import test from 'node:test';
import assert from 'node:assert/strict';
import {mkdtempSync,rmSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {createJiti} from 'jiti';
const dir=mkdtempSync(join(tmpdir(),'codex-queue-durable-'));
process.env.PI_CODING_AGENT_DIR=dir;
const jiti=createJiti(import.meta.url,{alias:{'server-only':'next/dist/compiled/server-only/empty.js'}});
const {CodexRuntime}=await jiti.import('./codex-engine.ts');
const {runPromptDelivery,getPromptReceipt,getUncommittedPromptSubmissions,createPromptDeliveryStore}=await jiti.import('../prompt-delivery.ts');
test.after(()=>rmSync(dir,{recursive:true,force:true}));
test('Codex queue admission and synthetic handoff cannot release original; only native echo commits',async()=>{
 const id='codex:'+crypto.randomUUID(),requestId=crypto.randomUUID(),message='不能因弱网丢失的队列原文';
 const meta={id:id.slice(6),cwd:'/fixture',title:'fixture',status:'running',connected:true,sequence:1,submissions:[]};
 const runtime=new CodexRuntime(id,'isolated',{epoch:'e',sequence:1,rows:[],meta});runtime.json=async()=>({status:'queued'});
 const command={type:'prompt',message,requestId,streamingBehavior:'followUp'};
 await runPromptDelivery(id,requestId,command,()=>runtime.send(command));
 assert.equal(getPromptReceipt(id,requestId).status,'accepted');assert.equal(getUncommittedPromptSubmissions(id)[0].message,message);
 assert.equal(createPromptDeliveryStore(dir).pending(id)[0].message,message,'server restart restores the exact inbox');
 const row={key:'u',requestId,deliveryConfirmed:false,role:'user',kind:'userMessage',turnId:'t',order:1,version:'placeholder',text:message};
 await runtime.accept({epoch:'e',sequence:2,rows:[row],meta});assert.equal(getPromptReceipt(id,requestId).status,'accepted');assert.equal(runtime.hasConfirmedDelivery(requestId),false);
 const events=[];runtime.listeners.add(e=>events.push(e.type));await runtime.accept({epoch:'e',sequence:3,rows:[{...row,deliveryConfirmed:true,version:'native-echo'}],meta});
 assert.equal(runtime.hasConfirmedDelivery(requestId),true);assert.equal(getPromptReceipt(id,requestId).status,'committed');assert.deepEqual(getUncommittedPromptSubmissions(id),[]);assert(events.indexOf('message_end')<events.indexOf('prompt_delivery'));
});
