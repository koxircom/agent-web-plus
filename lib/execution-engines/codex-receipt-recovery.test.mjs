import test from 'node:test';
import assert from 'node:assert/strict';
import {mkdtempSync,rmSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {createJiti} from 'jiti';
const dir=mkdtempSync(join(tmpdir(),'codex-receipt-'));process.env.PI_CODING_AGENT_DIR=dir;
const jiti=createJiti(import.meta.url,{alias:{'server-only':'next/dist/compiled/server-only/empty.js'}});
const engine=await jiti.import('./codex-engine.ts');
const inbox=await jiti.import('../prompt-delivery.ts');
const settings=await jiti.import('../execution-engine-settings.ts');
await settings.saveExecutionEngineSettings({codex:{enabled:true,url:'http://127.0.0.1:1'}});
test.after(()=>rmSync(dir,{recursive:true,force:true}));
test('persisted native receipt commits without a recent timeline, admission or text matching',async t=>{
 const oldFetch=globalThis.fetch;t.after(()=>globalThis.fetch=oldFetch);
 const id='codex:'+crypto.randomUUID(),requestId=crypto.randomUUID(),other=crypto.randomUUID(),text='identical input';
 for(const rid of [requestId,other])await inbox.runPromptDelivery(id,rid,{message:text,images:[{data:'eA==',mimeType:'image/png'}]},async()=>({}));
 let receipt={status:'accepted',deliveryConfirmed:false},calls=[];
 globalThis.fetch=async(url,init)=>{const path=new URL(url).pathname;calls.push([path,init.method]);
  if(path==='/api/login')return Response.json({});if(path==='/api/auth')return Response.json({csrf:'fixture'});
  assert(path.includes('/submissions/'+engine.submissionUuid(requestId)),'receipt reads must not attach/read a runtime');return Response.json({id:engine.submissionUuid(requestId),...receipt});};
 await engine.reconcileCodexDelivery(id,requestId);assert.equal(inbox.getPromptReceipt(id,requestId).status,'accepted');
 receipt={status:'unknown',deliveryConfirmed:false};await engine.reconcileCodexDelivery(id,requestId);assert.equal(inbox.getPromptReceipt(id,requestId).status,'unconfirmed');
 receipt={id:engine.submissionUuid(other),status:'accepted',deliveryConfirmed:true};await engine.reconcileCodexDelivery(id,requestId);assert.equal(inbox.getPromptReceipt(id,requestId).status,'unconfirmed','a different native ID cannot release this original');
 receipt={status:'unknown',deliveryConfirmed:true};assert.equal(await engine.reconcileCodexDelivery(id,requestId),'committed');
 assert.equal(inbox.getPromptReceipt(id,requestId).status,'committed');
 assert.equal(inbox.getPromptReceipt(id,other).status,'accepted');assert.equal(inbox.getUncommittedPromptSubmissions(id)[0].images[0].data,'eA==');
 assert.equal(inbox.createPromptDeliveryStore(dir).receipt(id,requestId).status,'committed');
 assert.equal(calls.filter(([p,m])=>m==='POST'&&p!=='/api/login').length,0);
});
